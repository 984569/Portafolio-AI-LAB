"""Bounded, descriptive comparisons with explicit chronological and seed limits."""

import math
from collections import defaultdict
from collections.abc import Mapping, Sequence
from functools import lru_cache
from typing import Any

import numpy as np
from numpy.typing import NDArray
from portfolio_core import financial_metrics

from .temporal import WALK_FORWARD_FOLDS, canonical_date


@lru_cache(maxsize=2)
def _fixed_fold_dates(fold_id: str) -> tuple[str, ...]:
    import exchange_calendars as xcals

    fold = next(item for item in WALK_FORWARD_FOLDS if item["fold_id"] == fold_id)
    calendar = xcals.get_calendar("XNYS", start=fold["eval_start"], end=fold["eval_end"])
    dates = tuple(str(stamp.date()) for stamp in calendar.sessions)
    return tuple(stamp for stamp in dates if fold["eval_start"] <= stamp <= fold["eval_end"])


def _result_arrays(result: Mapping[str, Any]) -> tuple[tuple[str, ...], NDArray[np.float64]]:
    points = result.get("equity")
    if not isinstance(points, list) or len(points) < 2:
        raise ValueError("A result requires at least two equity observations")
    dates = tuple(canonical_date(point.get("date"), "equity date") for point in points)
    if any(first >= second for first, second in zip(dates, dates[1:], strict=False)):
        raise ValueError("Equity dates must be sorted and unique")
    if dates[-1] >= "2024-01-01":
        raise ValueError("Final2024 cannot enter Stage3 evaluation/statistics")
    values = np.asarray([point.get("equity") for point in points], dtype=np.float64)
    if not np.isfinite(values).all() or (values <= 0).any():
        raise ValueError("Equity must be positive and finite")
    reported = np.asarray([point.get("net_return") for point in points], dtype=np.float64)
    actual = values[1:] / values[:-1] - 1
    if (
        not np.isfinite(reported).all()
        or not np.isclose(reported[0], 0, atol=1e-12)
        or not (np.allclose(reported[1:], actual, rtol=1e-10, atol=1e-12))
    ):
        raise ValueError("Reported net returns must match the canonical equity curve")
    config = result.get("manifest", {}).get("configuration", {})
    metrics = result.get("metrics", {})
    expected = financial_metrics(
        values, config.get("risk_free_rate", 0), metrics.get("total_costs", float("nan"))
    )
    for key, value in expected.items():
        reported_value = metrics.get(key)
        if value is None:
            if reported_value is not None:
                raise ValueError("Reported base metric must match canonical accounting")
        elif (
            isinstance(reported_value, bool)
            or not isinstance(reported_value, (int, float))
            or not math.isfinite(reported_value)
            or not math.isclose(reported_value, value, rel_tol=1e-9, abs_tol=1e-10)
        ):
            raise ValueError("Reported base metric must match canonical accounting")
    return dates, values


def _seed(result: Mapping[str, Any]) -> int:
    value = result.get("manifest", {}).get("configuration", {}).get("seed")
    if isinstance(value, bool) or not isinstance(value, int) or not 0 <= value <= 2147483647:
        raise ValueError("Each result must record a valid integer seed")
    return value


def _strategy(result: Mapping[str, Any]) -> str:
    config = result.get("manifest", {}).get("configuration", {})
    strategy = config.get("strategy", config.get("algorithm"))
    if strategy not in {"ppo", "ddpg", "equal_weight", "markowitz"}:
        raise ValueError("Result must identify its strategy")
    return str(strategy)


def extra_metrics(result: Mapping[str, Any]) -> dict[str, Any]:
    """Derived CAGR252, turnover and empirical target-weight distribution.

    Cost/return base metrics remain those generated by shared accounting. Weight
    standard deviation describes allocation variability across dates, not an
    inferential confidence interval. All trading dates include the entry action.
    """
    dates, values = _result_arrays(result)
    allocations = result.get("allocations")
    if not isinstance(allocations, list) or len(allocations) != len(values) - 1:
        raise ValueError("One allocation is required per realized portfolio interval")
    if tuple(item.get("date") for item in allocations) != dates[:-1]:
        raise ValueError("Allocation dates must align with execution closes")
    first_weights = allocations[0].get("weights")
    if not isinstance(first_weights, dict) or not first_weights:
        raise ValueError("Allocation weights must be nonempty asset mappings")
    assets = tuple(first_weights)
    if any(set(item.get("weights", {})) != set(assets) for item in allocations):
        raise ValueError("Every allocation must use the same universe")
    weights = np.asarray(
        [[item["weights"][asset] for asset in assets] for item in allocations], dtype=np.float64
    )
    if (
        not np.isfinite(weights).all()
        or (weights < 0).any()
        or (weights > 1).any()
        or not (np.allclose(weights.sum(axis=1), 1, rtol=0, atol=1e-8))
    ):
        raise ValueError("Weights must be finite, long-only and sum to one")
    turnover = np.asarray([item.get("turnover") for item in allocations], dtype=np.float64)
    costs = np.asarray([item.get("cost") for item in allocations], dtype=np.float64)
    if (
        not np.isfinite(turnover).all()
        or not np.isfinite(costs).all()
        or ((turnover < 0).any() or (costs < 0).any())
    ):
        raise ValueError("Turnover and costs must be finite and nonnegative")
    if not math.isclose(
        math.fsum(costs.tolist()), result["metrics"]["total_costs"], rel_tol=1e-9, abs_tol=1e-10
    ):
        raise ValueError("Allocation costs must match the canonical total fee metric")
    try:
        annualized: float | None = math.expm1(
            (math.log(float(values[-1])) - math.log(float(values[0]))) * 252 / (len(values) - 1)
        )
    except OverflowError:
        annualized = None
    return {
        "annualized_return": annualized,
        "annualized_return_definition": "exp(log(V_end/V_start)*252/net_return_count)-1",
        "annualized_return_status": "defined" if annualized is not None else "overflow",
        "annualization_factor": 252,
        "intervals": len(values) - 1,
        "turnover_total": float(math.fsum(turnover.tolist())),
        "turnover_mean": float(np.mean(turnover)),
        "transaction_costs": float(math.fsum(costs.tolist())),
        "weight_distribution": {
            asset: {
                "mean": float(weights[:, index].mean()),
                "std_across_dates": float(weights[:, index].std(ddof=0)),
                "min": float(weights[:, index].min()),
                "max": float(weights[:, index].max()),
                "last_target": float(weights[-1, index]),
            }
            for index, asset in enumerate(assets)
        },
    }


def seed_summary(results: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Report every independent seed of one strategy, never selecting the best.

    Standard deviation is sample ddof1 and undefined for one seed. This is
    optimization-seed dispersion on the same market window, not market uncertainty.
    Duplicate seeds and mixed strategy/date/economic inputs are rejected.
    """
    if not results:
        raise ValueError("At least one result is required")
    seeds = [_seed(result) for result in results]
    if len(set(seeds)) != len(seeds):
        raise ValueError("Seed summary requires one run per independent seed")
    strategies = {_strategy(result) for result in results}
    if len(strategies) != 1:
        raise ValueError("Seed summary groups exactly one strategy")
    dates = [_result_arrays(result)[0] for result in results]
    if any(item != dates[0] for item in dates[1:]):
        raise ValueError("Seed results must share the same evaluation dates")
    economic_fields = (
        "dataset_id",
        "lookback",
        "initial_capital",
        "transaction_cost_bps",
        "risk_free_rate",
    )
    configurations = [result.get("manifest", {}).get("configuration", {}) for result in results]
    reference = tuple(configurations[0].get(key) for key in economic_fields)
    if any(
        tuple(config.get(key) for key in economic_fields) != reference for config in configurations
    ):
        raise ValueError("Seed results must share economic and dataset assumptions")
    metric_rows = [{**result["metrics"], **extra_metrics(result)} for result in results]
    names = (
        "cumulative_return",
        "annualized_return",
        "sharpe_ratio",
        "annualized_volatility",
        "max_drawdown",
        "final_equity",
        "total_costs",
        "turnover_total",
        "turnover_mean",
    )
    summaries: dict[str, Any] = {}
    for name in names:
        values = [float(row[name]) for row in metric_rows if row.get(name) is not None]
        if any(not math.isfinite(value) for value in values):
            raise ValueError("Seed metric values must be finite or null")
        summaries[name] = {
            "available_count": len(values),
            "mean": math.fsum(values) / len(values) if values else None,
            "std": float(np.std(values, ddof=1)) if len(values) > 1 else None,
            "min": min(values) if values else None,
            "max": max(values) if values else None,
        }
    return {
        "strategy": next(iter(strategies)),
        "n_runs": len(results),
        "seeds": seeds,
        "metrics": summaries,
        "all_seeds_reported": True,
        "best_seed_selected": False,
        "interpretation": (
            "Seed dispersion conditional on one fixed market period; not market uncertainty"
        ),
    }


def paired_block_bootstrap(
    result_a: Mapping[str, Any],
    result_b: Mapping[str, Any],
    seed: int = 42,
    *,
    block_length: int = 20,
    resamples: int = 1000,
    confidence: float = 0.95,
) -> dict[str, Any]:
    """Circular paired moving-block CI for annualized mean net-return difference.

    The same sampled dates are used for both portfolios. This preserves local
    serial dependence approximately, not full regime dependence. It is exploratory,
    conditional on the supplied runs, and not corrected for multiple comparisons.
    A confidence interval is not a causal/superiority claim or a final holdout test.
    """
    dates_a, values_a = _result_arrays(result_a)
    dates_b, values_b = _result_arrays(result_b)
    if dates_a != dates_b:
        raise ValueError("Paired bootstrap requires identical valuation dates")
    economic_fields = (
        "dataset_id",
        "lookback",
        "initial_capital",
        "transaction_cost_bps",
        "risk_free_rate",
    )
    config_a = result_a.get("manifest", {}).get("configuration", {})
    config_b = result_b.get("manifest", {}).get("configuration", {})
    if any(config_a.get(key) != config_b.get(key) for key in economic_fields):
        raise ValueError("Paired portfolios must share dataset/economic assumptions")
    extra_metrics(result_a)
    extra_metrics(result_b)
    if isinstance(seed, bool) or not isinstance(seed, int) or not 0 <= seed <= 2147483647:
        raise ValueError("Bootstrap seed must be a valid integer")
    if (
        isinstance(block_length, bool)
        or not isinstance(block_length, int)
        or not 1 <= block_length <= 252
    ):
        raise ValueError("block_length must be an integer between1 and252")
    if (
        isinstance(resamples, bool)
        or not isinstance(resamples, int)
        or not 100 <= resamples <= 10000
    ):
        raise ValueError("resamples must be an integer between100 and10000")
    if (
        isinstance(confidence, bool)
        or not isinstance(confidence, (int, float))
        or not 0 < confidence < 1
    ):
        raise ValueError("confidence must lie strictly between0 and1")
    difference = values_a[1:] / values_a[:-1] - values_b[1:] / values_b[:-1]
    count = len(difference)
    result: dict[str, Any] = {
        "statistic": "annualized_mean_net_return_difference_a_minus_b",
        "estimate": float(np.mean(difference) * 252),
        "confidence": float(confidence),
        "observations": count,
        "block_length": block_length,
        "resamples": resamples,
        "seed": seed,
        "status": "insufficient_data",
        "lower": None,
        "upper": None,
        "p_value": None,
        "holdout_evaluated": False,
        "limitations": [
            "Exploratory serial-dependence approximation, not a causal superiority test",
            "Conditional on these models/seeds and market period; no multiplicity correction",
            "Not a substitute for protocol-locked2024 final evaluation",
        ],
    }
    if count < block_length:
        return result
    rng = np.random.default_rng(seed)
    blocks = math.ceil(count / block_length)
    offsets = np.arange(block_length)
    estimates = np.empty(resamples, dtype=np.float64)
    for index in range(resamples):
        starts = rng.integers(0, count, size=blocks)
        samples = ((starts[:, None] + offsets) % count).ravel()[:count]
        estimates[index] = float(np.mean(difference[samples]) * 252)
    tail = (1 - confidence) / 2
    result.update(
        status="computed",
        lower=float(np.quantile(estimates, tail)),
        upper=float(np.quantile(estimates, 1 - tail)),
    )
    return result


def select_candidate(fold_reports: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Rank one algorithm's complete predeclared walk-forward candidates.

    Input rows: {candidate_id: str, fold_id: str, result: Result}. Every candidate
    must include both fixed folds with one common development seed. Results must
    record training_end and requested_evaluation in their manifests and contain
    every XNYS close in the fixed fold (no favorable subperiod). No2022–2023
    value is accepted for selection. Tie-break: lexicographic candidate ID.
    """
    if not fold_reports:
        raise ValueError("Walk-forward reports cannot be empty")
    folds = {fold["fold_id"]: fold for fold in WALK_FORWARD_FOLDS}
    grouped: dict[str, dict[str, float | None]] = defaultdict(dict)
    dates_by_fold: dict[str, tuple[str, ...]] = {}
    seeds: set[int] = set()
    strategies: set[str] = set()
    for row in fold_reports:
        candidate, fold_id = row.get("candidate_id"), row.get("fold_id")
        if (
            not isinstance(candidate, str)
            or not candidate
            or len(candidate) > 100
            or not isinstance(fold_id, str)
            or fold_id not in folds
        ):
            raise ValueError("Candidate and predeclared fold identifiers are required")
        fold = folds[fold_id]
        result = row.get("result")
        if not isinstance(result, Mapping):
            raise ValueError("Each fold must include its actual result")
        dates, _ = _result_arrays(result)
        extra_metrics(result)
        manifest = result.get("manifest", {})
        requested = manifest.get("requested_evaluation", {})
        if manifest.get("training_end") != fold["train_end"] or requested != {
            "start": fold["eval_start"],
            "end": fold["eval_end"],
        }:
            raise ValueError("Candidate report does not match its fixed chronological protocol")
        if dates[0] < fold["eval_start"] or dates[-1] > fold["eval_end"]:
            raise ValueError("Candidate selection cannot consume later evaluation periods")
        if dates != _fixed_fold_dates(fold_id):
            raise ValueError("Candidate selection requires the complete predeclared XNYS fold")
        if fold_id in dates_by_fold and dates_by_fold[fold_id] != dates:
            raise ValueError("Candidate fold dates must align exactly")
        dates_by_fold[fold_id] = dates
        if fold_id in grouped[candidate]:
            raise ValueError("Duplicate candidate/fold result")
        sharpe = result.get("metrics", {}).get("sharpe_ratio")
        if sharpe is not None and (
            isinstance(sharpe, bool)
            or not isinstance(sharpe, (int, float))
            or not math.isfinite(sharpe)
        ):
            raise ValueError("Fold Sharpe must be finite or null")
        grouped[candidate][fold_id] = float(sharpe) if sharpe is not None else None
        seeds.add(_seed(result))
        strategies.add(_strategy(result))
    if len(seeds) != 1 or len(strategies) != 1 or not strategies <= {"ppo", "ddpg"}:
        raise ValueError("Selection requires one algorithm and one fixed development seed")
    scores: list[dict[str, Any]] = []
    for candidate, values in sorted(grouped.items()):
        if set(values) != set(folds):
            raise ValueError("Every candidate must report every predeclared fold")
        finite = [value for value in values.values() if value is not None]
        scores.append(
            {
                "candidate_id": candidate,
                "fold_scores": dict(values),
                "mean_sharpe": math.fsum(finite) / len(finite)
                if len(finite) == len(folds)
                else None,
            }
        )
    ranked = sorted(
        (item for item in scores if item["mean_sharpe"] is not None),
        key=lambda item: (-item["mean_sharpe"], item["candidate_id"]),
    )
    return {
        "status": "selected" if ranked else "no_finite_scores",
        "selected_candidate": ranked[0]["candidate_id"] if ranked else None,
        "algorithm": next(iter(strategies)),
        "development_seed": next(iter(seeds)),
        "selection_metric": "mean_predeclared_fold_sharpe",
        "scores": scores,
        "tie_break": "lexicographic candidate_id",
        "folds": list(WALK_FORWARD_FOLDS),
        "validation_2022_2023_used": False,
        "holdout_evaluated": False,
        "limitation": "Small fixed candidate/fold experiment; selected does not mean optimal",
    }
